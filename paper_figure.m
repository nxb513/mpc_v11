function fh = paper_figure(width_mm, height_mm)
% PAPER_FIGURE Figure sized for a journal page (84 mm single-column or 174 mm
% double-column width) with Arial 8 pt text, 7 pt legends, 0.5 pt axes, 1 pt
% data lines, a light grid and a box. Titles are not used; panels are labelled
% (a), (b), ... and described in the caption.
fh = figure('Color', 'w', 'Units', 'centimeters', 'Position', [2, 2, width_mm / 10, height_mm / 10], ...
    'PaperUnits', 'centimeters', 'PaperSize', [width_mm / 10, height_mm / 10]);
set(fh, 'DefaultAxesFontName', 'Arial', 'DefaultAxesFontSize', 8, ...
    'DefaultTextFontName', 'Arial', 'DefaultTextFontSize', 8, ...
    'DefaultLegendFontName', 'Arial', 'DefaultLegendFontSize', 7, ...
    'DefaultAxesLineWidth', 0.5, 'DefaultLineLineWidth', 1.0, ...
    'DefaultAxesBox', 'on', 'DefaultAxesGridAlpha', 0.15, ...
    'DefaultAxesXGrid', 'on', 'DefaultAxesYGrid', 'on', ...
    'DefaultAxesTitleFontWeight', 'normal', 'DefaultAxesTitleFontSizeMultiplier', 1, ...
    'DefaultAxesLabelFontSizeMultiplier', 1);
end
