function fh = paper_figure(width_mm, height_mm)
% PAPER_FIGURE Figure sized for a journal page (174 mm double-column width or
% 84 mm single-column width), Arial 8 pt, white background, no title.
fh = figure('Color', 'w', 'Units', 'centimeters', 'Position', [2, 2, width_mm / 10, height_mm / 10], ...
    'PaperUnits', 'centimeters', 'PaperSize', [width_mm / 10, height_mm / 10]);
set(fh, 'DefaultAxesFontName', 'Arial', 'DefaultAxesFontSize', 8, ...
    'DefaultTextFontName', 'Arial', 'DefaultTextFontSize', 8, ...
    'DefaultLegendFontName', 'Arial', 'DefaultLegendFontSize', 7, ...
    'DefaultAxesLineWidth', 0.6, 'DefaultLineLineWidth', 1.0);
end
